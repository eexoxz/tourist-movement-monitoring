export const adminTranslationKeys = Object.keys(englishCatalog.admin) as AdminCopyKey[];
const englishKeys = new Map(adminTranslationKeys.map((key) => [englishCatalog.admin[key], key]));
const normalizedEnglishKeys = new Map(adminTranslationKeys.map((key) => [englishCatalog.admin[key]?.toLowerCase(), key]));

export function translateAdminEnglish(locale: Locale, source: string) {
  const key = englishKeys.get(source) ?? normalizedEnglishKeys.get(source.toLowerCase());
  return key ? translateAdmin(locale, key) : undefined;
}

export function englishAdminSource(locale: Locale, text: string) {
  const key = adminTranslationKeys.find((key) => translateAdmin(locale, key) === text);
  return key ? englishCatalog.admin[key] : undefined;
}

export function hasDirectAdminTranslation(locale: Locale, key: AdminCopyKey) {
  return Boolean(getLocaleCatalog(locale)?.admin[key] ?? coverageText(locale, englishCatalog.admin[key] ?? key));
}

export function translateAdmin(locale: Locale, key: AdminCopyKey, values: Record<string, string | number> = {}) {
  const template = getLocaleCatalog(locale)?.admin[key] ?? coverageText(locale, englishCatalog.admin[key] ?? key) ?? englishCatalog.admin[key] ?? key;

  return Object.entries(values).reduce((text, [name, value]) => text.replaceAll(`{${name}}`, String(value)), template);
}
