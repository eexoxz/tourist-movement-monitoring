const STORAGE_KEY = "tourist-movement-monitoring:locale";

export const localeOptions: Array<{ value: Locale; labelKey: TranslationKey }> = [
  { value: "en", labelKey: "language.english" },
  { value: "ms", labelKey: "language.malay" },
  { value: "zh", labelKey: "language.chinese" },
  { value: "ja", labelKey: "language.japanese" },
  { value: "ko", labelKey: "language.korean" },
  { value: "pt", labelKey: "language.portuguese" },
  { value: "ta", labelKey: "language.tamil" },
  { value: "es", labelKey: "language.spanish" },
  { value: "fr", labelKey: "language.french" },
];

export function isLocale(value: string): value is Locale {
  return localeOptions.some((option) => option.value === value);
}

export function loadLocale() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    return saved && isLocale(saved) ? saved : "en";
  } catch {
    return "en";
  }
}

export function saveLocale(locale: Locale) {
  try {
    localStorage.setItem(STORAGE_KEY, locale);
  } catch {
    // The selected language still works when browser storage is blocked.
  }
}

export const translationKeys = Object.keys(englishCatalog.main) as TranslationKey[];

function englishText(key: TranslationKey) {
  return englishCatalog.main[key] ?? key;
}

const englishKeys = new Map(translationKeys.map((key) => [englishText(key), key]));
const normalizedEnglishKeys = new Map(translationKeys.map((key) => [englishText(key).toLowerCase().replace(/[.,]$/, ""), key]));

export function translateEnglish(locale: Locale, source: string) {
  const key = englishKeys.get(source) ?? normalizedEnglishKeys.get(source.toLowerCase().replace(/[.,]$/, ""));
  return key ? translate(locale, key) : undefined;
}

export function englishTranslationSource(locale: Locale, text: string) {
  const key = translationKeys.find((key) => translate(locale, key) === text);
  return key ? englishText(key) : undefined;
}

export function hasDirectTranslation(locale: Locale, key: TranslationKey) {
  return Boolean(getLocaleCatalog(locale)?.main[key] ?? coverageText(locale, englishText(key)));
}

export function translate(locale: Locale, key: TranslationKey) {
  return getLocaleCatalog(locale)?.main[key] ?? coverageText(locale, englishText(key)) ?? englishText(key);
}
